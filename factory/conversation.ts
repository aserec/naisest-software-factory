// What the factory says on a work item or a change, and what people say back (GLOSSARY.md: Request, Paused run, Stop, Resume).
// The factory's notes are the only place a paused run's state and the request cursor live, so every note is written and read here:
// the writer and its reader sit side by side, and no other module knows a note's text. The same goes for the rule for a request:
// a comment by a trusted person, not by the factory, that mentions `@factory`, after the cursor.
import type { Request } from "./record";
import type { ChangeRef, CodeHost, Comment, FactoryState, Judge, PersonRef, Tracker, TicketRef } from "./seams";
import { INJECTION_LIMIT, buildTriageState, injectionQuestion } from "./triage";

// The line every note and change text from the factory starts with, on every host.
export const AI_LINE = "> *This was generated by AI in the software factory.*";

// GitLab runs quick actions (/merge, /label, /close ...) from any line that starts with "/", as the bot.
// Notes and change descriptions carry agent and reviewer text, so a zero-width space goes before each such "/".
export const noQuickActions = (text: string) => text.replace(/^([ \t]*)\//gm, "$1\u200B/");

// --- requests -------------------------------------------------------------------------------------------------

const COMMANDS = ["@factory stop", "@factory resume"];
const MENTION = /(^|[^\w@.-])@factory(?![\w-])/i;

export function isRequest(body: string): boolean {
  if (body.split("\n").some((l) => COMMANDS.includes(l.trim().toLowerCase()))) return false;
  return MENTION.test(body);
}

// A line that stops the run, and the bare stop or resume comment: commands to the factory, not requests.
export const hasStopLine = (body: string) => body.split("\n").some((l) => l.trim().toLowerCase() === COMMANDS[0]);
export const isBareCommand = (body: string) => COMMANDS.includes(body.trim());

// The comments people wrote: the factory's own are left out, even when they quote a command.
export const byPeople = (comments: Comment[]) => comments.filter((c) => !c.byFactory);

export const later = (a: string | undefined, b: string | undefined): string | undefined =>
  a === undefined || b === undefined ? (a ?? b) : Date.parse(b) > Date.parse(a) ? b : a;

// The time of the factory's newest comment in the list, if it has one.
const newestByFactory = (comments: Comment[]): string | undefined => comments.filter((c) => c.byFactory).reduce<string | undefined>((t, c) => later(t, c.at), undefined);

// --- notes ----------------------------------------------------------------------------------------------------

// The note formats must not change: work items paused before a deploy carry the old ones.
const BLOCKED = "The factory stopped. A person must look at this.";
// Only the comment's last line: the reason above it can quote agent text with a run line of its own.
const BLOCKED_RUN = /\nBlocked run: pipeline (\d+)\s*$/;
const WAITING_RUN = /^Waiting run: pipeline (\d+)$/m;
const STOPPED_RUN = /^Stopped run: pipeline (\d+)$/m;
// The poller's comment when the dashboard cancelled a pipeline that did not stop in time. Such a run cannot be resumed.
const CANCEL_REASON = "Reason: pipeline cancelled from the dashboard";
const CURSOR = /^Requests read up to: (\S+)/m;
const READY_FOR = /^Ready for the request of: (\S+)$/m;
// Comments posted before the two duplicate kinds were told apart carry CLOSE_MARKER on a question too, so an old marker reads as a close.
const CLOSE_MARKER = "<!-- factory:dedupe -->";
const QUESTION_MARKER = "<!-- factory:dedupe-question -->";

// What a factory note says. `text` is the sentence people read; the lines after it are what the factory reads back.
export type Note =
  | { kind: "blocked"; reason: string; run?: string } // run: the pipeline to continue; none when the run cannot continue
  | { kind: "waiting"; run: string | undefined }
  // `@factory resume` continues a person's stop, the poller a switch stop once the switch is on again.
  | { kind: "stopped"; run: string; step: string; reason: string; change?: ChangeRef; buildRun?: string }
  | { kind: "cancelled"; user: PersonRef }
  | { kind: "readyFor"; text: string; person: PersonRef; cursor: string } // the factory set the work item ready for this person's request
  | { kind: "cursor"; text: string; at?: string } // the requests read up to `at`; without it, only the text
  | { kind: "duplicate_question"; text: string }
  | { kind: "duplicate_close"; text: string };

export function noteText(n: Note): string {
  switch (n.kind) {
    case "blocked":
      return `${BLOCKED}\n\n${n.reason}${n.run ? `\n\nBlocked run: pipeline ${n.run}` : ""}`;
    case "waiting":
      return `The author agent reached its usage limit. The factory tries again every hour and continues this run.\n\nWaiting run: pipeline ${n.run ?? "unknown"}`;
    case "stopped":
      return [
        n.reason.startsWith("switch off") ? "A dashboard switch stopped this run. The factory continues it when the switch is on again." : "A person stopped this run. Comment the line @factory resume to continue it.",
        "",
        `Stopped run: pipeline ${n.run}`,
        `Stopped step: ${n.step}`,
        `Reason: ${n.reason}`,
        ...(n.change ? [`Change: ${n.change}`, `Build run: ${n.buildRun ?? "unknown"}`] : []),
      ].join("\n");
    case "cancelled":
      return `The run was stopped from the dashboard by @${n.user}. The pipeline did not stop within 60 seconds, so it was cancelled. Resume is not possible. Use Restart.\n\n${CANCEL_REASON}`;
    case "readyFor":
      return `${n.text}\n\nReady for the request of: ${n.person}\n\nRequests read up to: ${n.cursor}`;
    case "cursor":
      return n.at ? `${n.text}\n\nRequests read up to: ${n.at}` : n.text;
    case "duplicate_question":
      return `${n.text}\n\n${QUESTION_MARKER}`;
    case "duplicate_close":
      return `${n.text}\n\n${CLOSE_MARKER}`;
  }
}

// What each kind of note holds when read back.
interface Fields {
  blocked: { run?: string };
  waiting: { run: string };
  // An old stopped note has only its run.
  stopped: { run: string; step?: string; reason?: string; change?: ChangeRef; buildRun?: string };
  cancelled: object;
  readyFor: { person: PersonRef };
  cursor: { cursor: string };
  duplicate_question: object;
  duplicate_close: object;
}
type Found = { [K in keyof Fields]: { kind: K; at: string } & Fields[K] }[keyof Fields];

const field = (body: string, name: string) => new RegExp(`^${name}: (.+)$`, "m").exec(body)?.[1];
const PARSE: { [K in keyof Fields]: (body: string) => Fields[K] | undefined } = {
  blocked: (b) => (b.includes(BLOCKED) ? { run: BLOCKED_RUN.exec(b)?.[1] } : undefined),
  waiting: (b) => {
    const run = WAITING_RUN.exec(b)?.[1];
    return run ? { run } : undefined;
  },
  stopped: (b) => {
    const run = STOPPED_RUN.exec(b)?.[1];
    if (!run) return undefined;
    const [step, reason, change] = [field(b, "Stopped step"), field(b, "Reason"), field(b, "Change")];
    return { run, ...(step && reason ? { step, reason, ...(change ? { change, buildRun: field(b, "Build run") } : {}) } : {}) };
  },
  cancelled: (b) => (b.split("\n").includes(CANCEL_REASON) ? {} : undefined),
  readyFor: (b) => {
    const person = READY_FOR.exec(b)?.[1];
    return person ? { person } : undefined;
  },
  cursor: (b) => {
    const cursor = CURSOR.exec(b)?.[1];
    return cursor ? { cursor } : undefined;
  },
  duplicate_question: (b) => (b.includes(QUESTION_MARKER) ? {} : undefined),
  duplicate_close: (b) => (b.includes(CLOSE_MARKER) ? {} : undefined),
};
// The kinds a read finds. A stopped read also finds a cancel note: the run cannot be resumed, only restarted.
const READS = { blocked: ["blocked"], waiting: ["waiting"], stopped: ["cancelled", "stopped"], readyFor: ["readyFor"], cursor: ["cursor"], duplicate: ["duplicate_question", "duplicate_close"] } as const;
export type ReadKind = keyof typeof READS;
export type Read<K extends ReadKind> = Extract<Found, { kind: (typeof READS)[K][number] }>;

// The newest note of this kind among the comments. Only the factory's own comments count: anyone who can comment could write
// the same lines. Only the newest counts: a person or the dashboard may have paused the run again since an older note.
export function newestNote<K extends ReadKind>(comments: Comment[], kind: K): Read<K> | undefined {
  let best: Found | undefined;
  for (const c of comments) {
    if (!c.byFactory || (best && !(Date.parse(c.at) > Date.parse(best.at)))) continue; // a tie goes to the first listed, which is the newest
    for (const k of READS[kind] as readonly (keyof Fields)[]) {
      const fields = PARSE[k](c.body);
      if (fields) {
        best = { kind: k, at: c.at, ...fields } as Found;
        break;
      }
    }
  }
  return best as Read<K> | undefined;
}

// The marker that tells the watcher a work item is its own and which finding it came from. It sits in the work item's text, not in a comment.
export const fingerprintMarker = (fp: string) => `<!-- factory:fingerprint ${fp} -->`;

// --- what a request gets back ---------------------------------------------------------------------------------

const WHAT: Partial<Record<FactoryState, string>> = {
  stopped: "Comment `@factory resume` to continue the run. The factory takes up this request once its change waits for a person.",
  waiting: "The run waits for the author agent's usage limit. The factory continues it within the hour and takes up this request once its change waits for a person.",
  ready: "The run starts soon. Write the request again once the change waits for a person.",
  done: "This work is done. Open a new work item for more.",
};

export function stateReply(author: PersonRef, state: FactoryState | undefined): string {
  const what = (state && WHAT[state]) ?? "The factory has not started work here. Add factory_ready to start.";
  return `@${author} The factory takes @factory requests only while its change waits for a person (factory_needs_approval). ${what}`;
}

// --- the conversation of a run --------------------------------------------------------------------------------

// One Tracker.trusted call per author for the run: the cache lives as long as the tracker does.
const trustOf = new WeakMap<Tracker, Map<string, Promise<boolean>>>();

export interface Conversation {
  // The requests after the cursor, oldest first, from the work item and from its open change. `change` is that change when it is open.
  // forReply: the requests only get a reply, so with no cursor at all the factory's newest comment on the work item counts too.
  requests(ref: TicketRef, forReply?: boolean): Promise<{ requests: Request[]; change?: { ref: ChangeRef; url: string } }>;
  // Every request on the work item, oldest first, whatever the cursor.
  itemRequests(ref: TicketRef): Promise<Comment[]>;
  // The requests on a change, in the list's order, that no answer or round has taken up: after the change's cursor and the work item's.
  unanswered(change: ChangeRef, ref: TicketRef, since: string): Promise<Comment[]>;
  // What the running agent gets: comments of trusted people on the work item and its change after `since`, oldest first.
  // `until`: the time of the newest comment read, trusted or not. `stop`: a trusted comment has a stop line; it is found before the
  // injection check, because it orders the factory and not the agent. When the judge fails, `comments` is empty and there is no
  // `until`: nothing is lost, the caller reads the same comments again.
  news(ref: TicketRef, since: string, change?: ChangeRef): Promise<{ until?: string; stop: boolean; comments: (Comment & { injection: boolean })[] }>;
  // Does the comment try to give an AI agent orders? Fails closed (a judge answer that is not a number counts as yes) and throws when the judge gives none.
  isInjection(c: Pick<Comment, "author" | "body">): Promise<boolean>;
  write(ref: TicketRef, note: Note): Promise<void>;
  writeOnChange(change: ChangeRef, note: Note): Promise<void>;
  // The factory's newest note of this kind on the work item.
  newest<K extends ReadKind>(ref: TicketRef, kind: K): Promise<Read<K> | undefined>;
}

export function conversation(seams: { tracker: Tracker; codeHost: CodeHost; judge: Judge }): Conversation {
  const { tracker, codeHost, judge } = seams;
  const trust = trustOf.get(tracker) ?? trustOf.set(tracker, new Map()).get(tracker)!;
  const trusted = (author: PersonRef) => {
    let p = trust.get(author);
    if (!p) {
      p = tracker.trusted(author);
      trust.set(author, p);
      p.catch(() => trust.delete(author)); // a failed check is asked again, not remembered
    }
    return p;
  };

  // The rule for a comment from a person: not the factory's, after the cursor, from a trusted author, and with `@factory` when only requests count.
  async function people(comments: Comment[], o: { after?: string; requestsOnly?: boolean }): Promise<Comment[]> {
    const out: Comment[] = [];
    for (const c of comments) {
      if (c.byFactory || (o.after !== undefined && Date.parse(c.at) <= Date.parse(o.after)) || (o.requestsOnly && !isRequest(c.body))) continue;
      if (await trusted(c.author)) out.push(c);
    }
    return out;
  }
  const oldestFirst = (list: Comment[]) => [...list].sort((a, b) => Date.parse(a.at) - Date.parse(b.at));

  const isInjection: Conversation["isInjection"] = async (c) => {
    const [a] = await judge.ask(buildTriageState(`Request by ${c.author}`, c.body, []), [injectionQuestion]);
    if (!a) throw new Error(`The judge gave no answer for "${injectionQuestion.id}"`);
    return !(a.probability < INJECTION_LIMIT);
  };

  return {
    async requests(ref, forReply = false) {
      const c = await codeHost.changeOfTicket(ref);
      const onItem = await tracker.comments(ref);
      const onChange = c ? await codeHost.changeComments(c.ref) : [];
      // No cursor line: the factory's newest comment on the change. With neither, nothing is read.
      const cursor = newestNote([...onItem, ...onChange], "cursor")?.cursor ?? newestByFactory(onChange) ?? (forReply ? newestByFactory(onItem) : undefined);
      if (cursor === undefined) return { requests: [] };
      const open = c?.open ? { ref: c.ref, url: c.url } : undefined;
      const on = (list: Comment[], where: Request["on"]) => people(list, { after: cursor, requestsOnly: true }).then((l) => l.map((x) => ({ author: x.author, body: x.body, at: x.at, on: where })));
      const requests = [...(await on(onItem, "work item")), ...(open ? await on(onChange, "change") : [])];
      return { requests: requests.sort((a, b) => Date.parse(a.at) - Date.parse(b.at)), ...(open ? { change: open } : {}) };
    },
    async itemRequests(ref) {
      return oldestFirst(await people(await tracker.comments(ref), { requestsOnly: true }));
    },
    async unanswered(change, ref, since) {
      const onChange = await codeHost.changeComments(change, since);
      const cursor = newestNote(onChange, "cursor")?.cursor;
      const requests = await people(onChange, { after: cursor, requestsOnly: true });
      if (requests.length === 0) return [];
      // The webhook answers on the work item, with its own cursor line: that counts for the change too.
      // No cursor line: the factory's newest comment on the change, else on the work item. With none, every request in the window.
      const onItem = await tracker.comments(ref);
      const seen = later(cursor, newestNote(onItem, "cursor")?.cursor) ?? newestByFactory(onChange) ?? newestByFactory(onItem);
      return requests.filter((x) => seen === undefined || Date.parse(x.at) > Date.parse(seen));
    },
    async news(ref, since, change) {
      const all = oldestFirst([...(await tracker.comments(ref, since)).reverse(), ...(change ? await codeHost.changeComments(change, since) : []).reverse()]);
      const kept = await people(all, {});
      const stop = kept.some((c) => hasStopLine(c.body));
      const comments: (Comment & { injection: boolean })[] = [];
      try {
        for (const c of kept) comments.push({ ...c, injection: await isInjection(c) });
      } catch (e) {
        console.log(`Judge failed for the comments of ticket ${ref}: ${String(e).slice(0, 300)}`);
        return { stop, comments: [] };
      }
      return { ...(all.length > 0 ? { until: all.reduce((latest, c) => later(latest, c.at)!, since) } : {}), stop, comments };
    },
    isInjection,
    write: (ref, note) => tracker.comment(ref, noteText(note)),
    writeOnChange: (change, note) => codeHost.commentChange(change, noteText(note)),
    async newest(ref, kind) {
      return newestNote(await tracker.comments(ref), kind);
    },
  };
}
