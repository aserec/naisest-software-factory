const COMMIT_TITLE = /^(feat|fix|docs|style|refactor|perf|test|build|ci|chore|revert)(\([^()]+\))?!?: \S.*$/;
const slug = (title: string) => title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 40).replace(/-+$/, "");

export interface CommitMessage { title: string; message: string }

// The agent's run/commit-message.md. A title that is not a conventional commit title of 72 characters or less becomes the ticket title.
export function commitMessage(ctx: StepContext, ticketUrl: string): CommitMessage {
  const [first = "", ...rest] = withoutMarks(ctx.repo.readFile("run/commit-message.md") ?? "").split(/\r?\n/);
  const given = first.trim();
  const title = COMMIT_TITLE.test(given) && given.length <= 72 ? given : withoutMarks(ctx.record.ticket!.title);
  const closing = `Ticket: ${ticketUrl}\n${runLine(ctx.ci.vars.run, ctx.ci.vars.runUrl)}\nThis was generated by AI in the software factory.`;
  return { title, message: [title, rest.join("\n").trim(), closing].filter(Boolean).join("\n\n") };
}

// The finish run finds this run's record through the run link (approval and manual merge paths).
// The code host adds the AI line and the closing line.
// links, failed and commit come from the gate; a later step reads them from the saved gate data.
export function changeText(ctx: StepContext, links: Record<string, string> = facts(ctx).images ?? {}, failed: string[] = facts(ctx).uploadFailed ?? [], commit: CommitMessage = need(facts(ctx).commit, "commit message")) {
  const testChanges = ctx.repo.readFile("run/test-changes.md");
  const proof = proofSection(facts(ctx).proof, links, failed);
  return { title: commit.title, body: [runLine(ctx.ci.vars.run, ctx.ci.vars.runUrl), `## Commit message\n\n${commit.message}`, ...(testChanges ? [`## Changed tests, and why\n\n${testChanges}`] : []), proof].join("\n\n") };
}

// The first try and 3 retries, with no wait. An image that never goes up is named in failed, and the run goes on.
async function attachAll(ctx: StepContext, images: Record<string, Buffer>) {
  const links: Record<string, string> = {};
  const failed: string[] = [];
  for (const [name, bytes] of Object.entries(images)) {
    for (let tries = 0; tries < 4 && !links[name]; tries++) links[name] = await ctx.codeHost.attach(name, bytes).catch((e) => (console.error(e.message), ""));
    if (!links[name]) failed.push(name);
  }
  return { links, failed };
}

export async function run(ctx: StepContext): Promise<StepResult> {
  const ref = ticketRef(ctx);
  const stop = await install(ctx);
  if (stop) return stop;
  const max = (await thresholds(ctx)).values.maxAgentRounds;
  // Done only when code review passed on the code the gate passed. A continued gate job may hold changes no review saw.
  let unreviewed = facts(ctx).resumeAt === "precommit-gate";
  let result;
  for (;;) {
    // A resumed run goes on from its last round. A check after the last fix counts as the last round, never one more.
    const start = Math.min(ctx.record.rounds.gate + 1, max);
    result = await precommitGate({ fix: (feedback) => fix(ctx, feedback), run: async (cmd) => {
      const r = await ctx.repo.run(cmd);
      // ponytail: the Repo seam gives ok, not the exit code; add it to Repo.run if the dashboard needs the real code.
      emit(ctx, "gate_check", { command: cmd, exitCode: r.ok ? 0 : 1, outputTail: r.output });
      return r;
    } }, need(facts(ctx).commands, ".factory.yml commands"), max, start);
    ctx.record = { ...ctx.record, rounds: { ...ctx.record.rounds, gate: result.rounds } };
    if (result.kind === "limit") return waiting(ctx, "precommit-gate", result.sessionId);
    if (result.kind === "stopped") return stopped(ctx, "precommit-gate", { session: result.sessionId, reason: stopReason(ctx) });
    if (result.kind === "blocked") return block(ctx, `The precommit-gate is not green after ${result.rounds} rounds.\n\n${result.open.map((o) => `\`\`\`\n${o}\n\`\`\``).join("\n\n")}`);
    if (!unreviewed && result.rounds === start) break; // passed with no fix since the last review
    // The rounds add up across passes, so this ends inside the review and gate round limits.
    await ctx.tracker.unmark(ref, "reviewed");
    // Its own code-review step, so the dashboard shows this review as a row after the gate's patch.
    const r = await withStep(ctx, "code-review", () => review(ctx, "precommit-gate"), { outcome: (r) => endOutcome(ctx, typeof r === "string" ? r : "next") });
    if (typeof r === "string") return r;
    if (!r.fixed) break; // review passed on the code the gate passed
    unreviewed = false; // the review fixed code: run the gate again
  }
  const commit = commitMessage(ctx, (await ctx.tracker.ticket(ref)).url);
  const { title, body: scanned } = changeText(ctx, {}, [], commit);
  // Scan before anything leaves the runner. The raw manifest holds the test tails, which the section does not show.
  if (findSecrets((await ctx.repo.diff()).text + scanned + (readProof(ctx.repo.readFile).raw ?? "")).length > 0) return block(ctx, "The change contains a secret-looking value, so the factory did not push it.");
  // Before attachAll: it uploads images, which is a write.
  const end = await endIfClosed(ctx);
  if (end) return end;
  const { links, failed } = await attachAll(ctx, { ...readImages(ctx.repo.readBytes, facts(ctx).proof?.proof), ...readVideo(ctx.repo.readBytes, facts(ctx).proof?.proof) });
  const { body } = changeText(ctx, links, failed, commit);
  const branch = `${changeBranchPrefix(ref)}${slug(withoutMarks(ctx.record.ticket!.title))}`;
  const sha = await ctx.repo.commitAndPush(branch, commit.message);
  const c = await ctx.codeHost.openChange(branch, title, body, ref);
  save(ctx, "precommit-gate", { passed: true, rounds: result.rounds, branch, sha, change: c.ref, changeUrl: c.url, images: links, uploadFailed: failed, commit });
  await ctx.tracker.mark(ref, "checked"); // after the secret scan: a change that is not pushed is not checked
  return "next";
}

export const main = () => runStep("precommit-gate", run);
if (isMain(import.meta.url)) await main();
