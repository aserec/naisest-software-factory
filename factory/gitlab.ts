import { findSecrets } from "./rules";
import { NotFactoryRunError } from "./seams";

export const STATE_LABELS = ["factory_ready", "factory_running", "factory_needs_info", "factory_needs_approval", "factory_waiting", "factory_stopped", "factory_blocked", "factory_done"] as const;
export type StateLabel = (typeof STATE_LABELS)[number];
export const GITLAB_URL = "https://gitlab.example.com";
// GitLab access level of the Developer role. Developers and above may command the factory.
export const DEVELOPER = 30;
export const AI_LINE = "> *This was generated by AI in the software factory.*";

// GitLab runs quick actions (/merge, /label, /close ...) from any line that starts with "/", as the bot.
// Notes and MR descriptions carry agent and reviewer text, so a zero-width space goes before each such "/".
export const noQuickActions = (text: string) => text.replace(/^([ \t]*)\//gm, "$1\u200B/");

export class GitLab {
  constructor(private baseUrl: string, private token: string, private fetchFn: typeof fetch = fetch) {}

  private async call(method: string, endpoint: string, body?: unknown): Promise<Response> {
    const form = body instanceof FormData; // fetch sets the multipart type itself
    const res = await this.fetchFn(`${this.baseUrl}/api/v4${endpoint}`, {
      method,
      headers: form ? { "PRIVATE-TOKEN": this.token } : { "PRIVATE-TOKEN": this.token, "Content-Type": "application/json" },
      body: body === undefined ? undefined : form ? body : JSON.stringify(body),
    });
    if (!res.ok) throw new Error(`GitLab ${method} ${endpoint} failed with status ${res.status}`);
    return res;
  }

  private async json(method: string, endpoint: string, body?: unknown) {
    return (await this.call(method, endpoint, body)).json();
  }

  // A GET that returns GitLab's own JSON. The tracker adapter maps it to factory words.
  async getJson(endpoint: string) {
    return this.json("GET", endpoint);
  }

  // How many work items with this label were created since the date, open or closed.
  async countCreatedSince(projectId: number, label: string, since: Date): Promise<number> {
    const res = await this.call("GET", `/projects/${projectId}/issues?labels=${label}&created_after=${encodeURIComponent(since.toISOString())}&per_page=1`);
    // Fail closed: a missing count would read as 0 and let the daily cap pass.
    const total = res.headers.get("X-Total")?.trim();
    if (!total || !Number.isFinite(Number(total))) throw new Error(`GitLab sent no usable X-Total count: ${JSON.stringify(total)}`);
    return Number(total);
  }

  async createWorkItem(projectId: number, title: string, description: string, labels: string[]) {
    const full = noQuickActions(description);
    if (findSecrets(`${title}\n${full}`).length > 0) throw new Error("Work item refused: it contains a secret");
    const w = await this.json("POST", `/projects/${projectId}/issues`, { title, description: full, labels: labels.join(",") });
    return { iid: w.iid as number, webUrl: w.web_url as string };
  }

  // Uploads a PNG to the project. The returned url works in the Markdown of a change of that project.
  async uploadFile(projectId: number, name: string, data: Buffer): Promise<string> {
    const form = new FormData();
    form.append("file", new Blob([new Uint8Array(data)], { type: "image/png" }), name);
    return (await (await this.call("POST", `/projects/${projectId}/uploads`, form)).json()).url as string;
  }

  async getProject(path: string) {
    const p = await this.json("GET", `/projects/${encodeURIComponent(path)}`);
    return { id: p.id as number, defaultBranch: p.default_branch as string };
  }


  async reopenWorkItem(projectId: number, iid: number): Promise<void> {
    await this.call("PUT", `/projects/${projectId}/issues/${iid}`, { state_event: "reopen" });
  }

  // The bot's own user id, so its own approvals and merges are not taken for a person's.
  async botUserId(): Promise<number> {
    return (await this.json("GET", "/user")).id;
  }

  async memberAccessLevel(projectId: number, userId: number): Promise<number> {
    try {
      return (await this.json("GET", `/projects/${projectId}/members/all/${userId}`)).access_level;
    } catch (e) {
      if (String(e).includes("status 404")) return 0;
      throw e;
    }
  }




  // Who last added this label, from the label history. The poller has no webhook that names the person.
  async labelAddedBy(projectId: number, iid: number, label: string): Promise<number | undefined> {
    const events: any[] = [];
    for (let page = 1; page; ) {
      const res = await this.call("GET", `/projects/${projectId}/issues/${iid}/resource_label_events?per_page=100&page=${page}`);
      events.push(...(await res.json()));
      page = Number(res.headers.get("X-Next-Page")) || 0;
    }
    return events.filter((e: any) => e.action === "add" && e.label?.name === label).at(-1)?.user?.id;
  }


  async setState(projectId: number, iid: number, label: StateLabel): Promise<void> {
    const others = STATE_LABELS.filter((l) => l !== label).join(",");
    await this.call("PUT", `/projects/${projectId}/issues/${iid}`, { add_labels: label, remove_labels: others });
  }

  async addLabel(projectId: number, iid: number, label: string): Promise<void> {
    await this.call("PUT", `/projects/${projectId}/issues/${iid}`, { add_labels: label });
  }

  async removeLabel(projectId: number, iid: number, label: string): Promise<void> {
    await this.call("PUT", `/projects/${projectId}/issues/${iid}`, { remove_labels: label });
  }

  private async note(endpoint: string, body: string): Promise<void> {
    const full = noQuickActions(`${AI_LINE}\n\n${body}`);
    if (findSecrets(full).length > 0) throw new Error("Comment refused: it contains a secret");
    await this.call("POST", endpoint, { body: full });
  }

  async comment(projectId: number, iid: number, body: string): Promise<void> {
    await this.note(`/projects/${projectId}/issues/${iid}/notes`, body);
  }

  async commentMergeRequest(projectId: number, mrIid: number, body: string): Promise<void> {
    await this.note(`/projects/${projectId}/merge_requests/${mrIid}/notes`, body);
  }

  async userId(username: string): Promise<number> {
    const list = await this.json("GET", `/users?username=${encodeURIComponent(username)}`);
    if (!list[0]) throw new Error(`GitLab user ${username} not found`);
    return list[0].id;
  }

  async assignWorkItem(projectId: number, iid: number, userId: number): Promise<void> {
    await this.call("PUT", `/projects/${projectId}/issues/${iid}`, { assignee_ids: [userId] });
  }

  async openMergeRequest(projectId: number, branch: string, target: string, title: string, description: string) {
    const mr = await this.json("POST", `/projects/${projectId}/merge_requests`, { source_branch: branch, target_branch: target, title, description: noQuickActions(description) });
    return { iid: mr.iid as number, webUrl: mr.web_url as string };
  }

  // A re-run reuses the open MR of the factory branch and updates its text.
  async upsertMergeRequest(projectId: number, branch: string, target: string, title: string, description: string) {
    const open = await this.json("GET", `/projects/${projectId}/merge_requests?state=opened&source_branch=${encodeURIComponent(branch)}`);
    if (!open[0]) return this.openMergeRequest(projectId, branch, target, title, description);
    // GitLab allows one open MR per source branch, so an MR with another target must be closed by a person.
    if (open[0].target_branch !== target) throw new Error(`Merge request !${open[0].iid} from ${branch} targets ${open[0].target_branch}, not ${target}`);
    await this.call("PUT", `/projects/${projectId}/merge_requests/${open[0].iid}`, { title, description: noQuickActions(description) });
    return { iid: open[0].iid as number, webUrl: open[0].web_url as string };
  }


  async approvedBy(projectId: number, mrIid: number): Promise<number[]> {
    const a = await this.json("GET", `/projects/${projectId}/merge_requests/${mrIid}/approvals`);
    return (a.approved_by ?? []).map((x: { user: { id: number } }) => x.user.id);
  }

  async assignMergeRequest(projectId: number, mrIid: number, userId: number): Promise<void> {
    await this.call("PUT", `/projects/${projectId}/merge_requests/${mrIid}`, { assignee_ids: [userId] });
  }

  // Merges now and returns the commit on the target branch. Call it only after the MR pipeline is "success".
  // GitLab uses the project's own squash setting.
  // sha is the reviewed head: GitLab refuses the merge if the branch moved since.
  async merge(projectId: number, mrIid: number, sha: string): Promise<string> {
    const mr = await this.json("PUT", `/projects/${projectId}/merge_requests/${mrIid}/merge`, { sha });
    return (mr.merge_commit_sha ?? mr.squash_commit_sha ?? mr.sha) as string;
  }

  // Branch-ref queries miss merge request pipelines, so read the MR's own list (newest first).
  // Only a pipeline for headSha counts: a green pipeline of an older commit says nothing about this one.
  async mergeRequestPipelineStatus(projectId: number, mrIid: number, headSha: string): Promise<"success" | "failed" | "running"> {
    const newest = (await this.json("GET", `/projects/${projectId}/merge_requests/${mrIid}/pipelines`))[0];
    if (newest?.sha !== headSha) return "running";
    const status = newest.status;
    if (status === "success") return "success";
    return status === "failed" || status === "canceled" ? "failed" : "running";
  }

  async revertMerge(projectId: number, sha: string, base: string) {
    // A unique name, so an earlier revert branch for the same commit does not get in the way.
    const branch = `factory/revert-${sha.slice(0, 8)}-${Date.now()}`;
    await this.call("POST", `/projects/${projectId}/repository/branches`, { branch, ref: base });
    await this.call("POST", `/projects/${projectId}/repository/commits/${sha}/revert`, { branch });
    return this.openMergeRequest(projectId, branch, base, `Revert ${sha.slice(0, 8)}`, `The ${base} pipeline failed after ${sha}. This reverts it.`);
  }

  // The newest successful decision job of a build pipeline. That job's artifacts hold run/ at the end of the
  // build: the record, the target clone and the Claude session.
  // Only a pipeline the bot's trigger started on the factory's default branch counts: anyone who can run
  // a pipeline in the factory project could otherwise upload a record that says "auto".
  private async decisionJob(projectId: number, pipelineId: number): Promise<number> {
    const p = await this.json("GET", `/projects/${projectId}/pipelines/${pipelineId}`);
    const { defaultBranch } = await this.getProject(String(projectId));
    const bot = await this.botUserId();
    if (p.source !== "trigger" || p.ref !== defaultBranch || p.user?.id !== bot) {
      throw new NotFactoryRunError(`Pipeline ${pipelineId} is not a factory build pipeline (source ${p.source}, ref ${p.ref}, user ${p.user?.id})`);
    }
    const jobs = await this.json("GET", `/projects/${projectId}/pipelines/${pipelineId}/jobs?per_page=100`);
    // A retried job leaves older ones behind. Take the newest successful one.
    const job = jobs
      .filter((j: { name: string; status: string }) => j.name === "decision" && j.status === "success")
      .sort((a: { id: number }, b: { id: number }) => b.id - a.id)[0];
    if (!job) throw new Error(`Pipeline ${pipelineId} has no successful decision job`);
    return job.id;
  }

  // The run record saved by a build pipeline, for the finish pipeline and for a resumed run.
  async buildRecord(projectId: number, pipelineId: number): Promise<unknown> {
    return this.json("GET", `/projects/${projectId}/jobs/${await this.decisionJob(projectId, pipelineId)}/artifacts/run/record.json`);
  }

  // The whole artifacts zip of a build pipeline, for a resumed run.
  async runArtifacts(projectId: number, pipelineId: number): Promise<ArrayBuffer> {
    return (await this.call("GET", `/projects/${projectId}/jobs/${await this.decisionJob(projectId, pipelineId)}/artifacts`)).arrayBuffer();
  }

  // "none": the pipeline was canceled or skipped, so it will never give a result. No pipeline yet is "running".
  async pipelineStatus(projectId: number, ref: string, sha: string): Promise<"success" | "failed" | "running" | "none"> {
    const list = await this.json("GET", `/projects/${projectId}/pipelines?ref=${encodeURIComponent(ref)}&sha=${sha}&per_page=1`);
    const status = list[0]?.status;
    if (status === "canceled" || status === "skipped") return "none";
    return status === "success" || status === "failed" ? status : "running";
  }

  async closeWorkItem(projectId: number, iid: number): Promise<void> {
    await this.call("PUT", `/projects/${projectId}/issues/${iid}`, { state_event: "close" });
  }
}
