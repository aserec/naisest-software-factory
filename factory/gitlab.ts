import { findSecrets } from "./rules";

export const STATE_LABELS = ["factory_ready", "factory_running", "factory_needs_info", "factory_needs_approval", "factory_waiting", "factory_paused", "factory_blocked", "factory_done"] as const;
export type StateLabel = (typeof STATE_LABELS)[number];
export const AI_LINE = "> *This was generated by AI in the software factory.*";

export class GitLab {
  constructor(private baseUrl: string, private token: string, private fetchFn: typeof fetch = fetch) {}

  private async call(method: string, endpoint: string, body?: unknown): Promise<Response> {
    const res = await this.fetchFn(`${this.baseUrl}/api/v4${endpoint}`, {
      method,
      headers: { "PRIVATE-TOKEN": this.token, "Content-Type": "application/json" },
      body: body === undefined ? undefined : JSON.stringify(body),
    });
    if (!res.ok) throw new Error(`GitLab ${method} ${endpoint} failed with status ${res.status}`);
    return res;
  }

  private async json(method: string, endpoint: string, body?: unknown) {
    return (await this.call(method, endpoint, body)).json();
  }

  async getProject(path: string) {
    const p = await this.json("GET", `/projects/${encodeURIComponent(path)}`);
    return { id: p.id as number, defaultBranch: p.default_branch as string };
  }

  async getWorkItem(projectId: number, iid: number) {
    const w = await this.json("GET", `/projects/${projectId}/issues/${iid}`);
    return {
      title: w.title as string,
      description: (w.description ?? "") as string,
      labels: w.labels as string[],
      assigneeIds: (w.assignees ?? []).map((a: { id: number }) => a.id),
    };
  }

  async memberAccessLevel(projectId: number, userId: number): Promise<number> {
    try {
      return (await this.json("GET", `/projects/${projectId}/members/all/${userId}`)).access_level;
    } catch (e) {
      if (String(e).includes("status 404")) return 0;
      throw e;
    }
  }

  async countLabeled(projectId: number, label: StateLabel): Promise<number> {
    const res = await this.call("GET", `/projects/${projectId}/issues?labels=${label}&state=opened&per_page=1`);
    return Number(res.headers.get("X-Total") ?? 0);
  }

  async setState(projectId: number, iid: number, label: StateLabel): Promise<void> {
    const others = STATE_LABELS.filter((l) => l !== label).join(",");
    await this.call("PUT", `/projects/${projectId}/issues/${iid}`, { add_labels: label, remove_labels: others });
  }

  async comment(projectId: number, iid: number, body: string): Promise<void> {
    const full = `${AI_LINE}\n\n${body}`;
    if (findSecrets(full).length > 0) throw new Error("Comment refused: it contains a secret");
    await this.call("POST", `/projects/${projectId}/issues/${iid}/notes`, { body: full });
  }

  async openMergeRequest(projectId: number, branch: string, target: string, title: string, description: string) {
    const mr = await this.json("POST", `/projects/${projectId}/merge_requests`, { source_branch: branch, target_branch: target, title, description });
    return { iid: mr.iid as number, webUrl: mr.web_url as string };
  }

  async assignMergeRequest(projectId: number, mrIid: number, userId: number): Promise<void> {
    await this.call("PUT", `/projects/${projectId}/merge_requests/${mrIid}`, { assignee_ids: [userId] });
  }

  async mergeWhenGreen(projectId: number, mrIid: number): Promise<void> {
    await this.call("PUT", `/projects/${projectId}/merge_requests/${mrIid}/merge`, { merge_when_pipeline_succeeds: true, auto_merge: true });
  }

  async pipelineStatus(projectId: number, ref: string, sha: string): Promise<"success" | "failed" | "running"> {
    const list = await this.json("GET", `/projects/${projectId}/pipelines?ref=${encodeURIComponent(ref)}&sha=${sha}&per_page=1`);
    const status = list[0]?.status;
    return status === "success" || status === "failed" ? status : "running";
  }

  async closeWorkItem(projectId: number, iid: number): Promise<void> {
    await this.call("PUT", `/projects/${projectId}/issues/${iid}`, { state_event: "close" });
  }
}
