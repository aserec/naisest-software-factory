// The shell's texts, then each part's file in dict/. A part may reuse a shell text without repeating it.
const PARTS = [board, run, insights, tools];
export const DICT = { es: Object.assign({}, SHELL.es, ...PARTS.map((p) => p.es)), de: Object.assign({}, SHELL.de, ...PARTS.map((p) => p.de)) } as Record<Exclude<Language, "en">, Record<string, string>>;

export type T = (text: string, values?: Record<string, string | number>) => string;

export const translator =
  (lang: Language): T =>
  (text, values) =>
    (lang === "en" ? text : (DICT[lang][text] ?? text)).replace(/\{(\w+)\}/g, (m, k: string) => (values && k in values ? String(values[k]) : m));
